import { cp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const deployDirectory = join(root, "deploy");
const pagesDirectory = join(deployDirectory, "pages");

const [workerSource, html, css, app] = await Promise.all([
  readFile(join(root, "src/index.js"), "utf8"),
  readFile(join(root, "public/index.html"), "utf8"),
  readFile(join(root, "public/styles.css"), "utf8"),
  readFile(join(root, "public/app.js"), "utf8"),
]);

const assetFallback = "    return withSecurityHeaders(await env.ASSETS.fetch(request));";
if (!workerSource.includes(assetFallback)) {
  throw new Error("src/index.js asset fallback changed; update the standalone generator");
}

const inlineAssets = [
  ["/index.html", { body: html, contentType: "text/html; charset=utf-8", cacheControl: "no-cache" }],
  ["/styles.css", { body: css, contentType: "text/css; charset=utf-8", cacheControl: "public, max-age=300" }],
  ["/app.js", { body: app, contentType: "text/javascript; charset=utf-8", cacheControl: "public, max-age=300" }],
];

const standaloneFallback = `    if (request.method !== "GET" && request.method !== "HEAD") {
      return withSecurityHeaders(
        new Response("Method not allowed", {
          status: 405,
          headers: { Allow: "GET, HEAD" },
        }),
      );
    }

    const assetPath = url.pathname === "/" ? "/index.html" : url.pathname;
    const asset = INLINE_ASSETS.get(assetPath);
    if (!asset) {
      return withSecurityHeaders(new Response("Not found", { status: 404 }));
    }

    return withSecurityHeaders(
      new Response(request.method === "HEAD" ? null : asset.body, {
        headers: {
          "Content-Type": asset.contentType,
          "Cache-Control": asset.cacheControl,
        },
      }),
    );`;

const generatedHeader = `// Generated by scripts/build-deploy-files.mjs.
// Paste this entire file into the Cloudflare Workers dashboard editor.
`;
const standaloneWorker = `${generatedHeader}const INLINE_ASSETS = new Map(${JSON.stringify(inlineAssets)});\n\n${workerSource.replace(assetFallback, standaloneFallback)}`;

await rm(deployDirectory, { recursive: true, force: true });
await mkdir(pagesDirectory, { recursive: true });
await writeFile(join(deployDirectory, "worker.js"), standaloneWorker);
await cp(join(root, "public"), pagesDirectory, { recursive: true });
await cp(join(root, "src/index.js"), join(pagesDirectory, "_worker.js"));

console.log("Generated deploy/worker.js and deploy/pages/");
